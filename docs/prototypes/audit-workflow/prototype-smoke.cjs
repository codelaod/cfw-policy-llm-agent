'use strict';
// Only a documentation-prototype check. No production code, cloud API or model is invoked.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const html = fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert.equal(new Set(ids).size, ids.length, 'duplicate static DOM ids');
const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1);
const code = scripts[0][1];
new vm.Script(code);
assert.match(html,/connect-src 'none'/);
assert.doesNotMatch(code,/\b(?:fetch|XMLHttpRequest|WebSocket|sendBeacon)\b/);
const elements = new Map(ids.map(id=>[id,{value:'',textContent:'',innerHTML:'',checked:false,disabled:false,hidden:false,addEventListener(){},classList:{toggle(){}}}]));
const context = vm.createContext({window:{},document:{getElementById:id=>elements.get(id)||null,querySelectorAll:()=>[],createElement:()=>({click(){}})},console,Blob:global.Blob,URL:global.URL,setTimeout});
vm.runInContext(code,context);
const app = context.window.mockAuditPrototype;
assert.ok(app);
const plain = x=>JSON.parse(JSON.stringify(x));
assert.match(elements.get('assetTable').textContent,/尚无资产/);
app.applyGuidance('GDE-04');
assert.equal(app.getState().tasks.length,0,'empty-state suggestion must not auto run');
app.applyGuidance('GDE-01');
assert.equal(app.getState().loaded,true);
app.applyGuidance('GDE-04');
assert.equal(app.getState().page,'audit');
assert.equal(app.getState().tasks.length,0,'suggestion opens preview, not execution');
assert.equal(app.getState().lastGuidance.catalogVersion,'guidance_v1');
app.reset();
assert.equal(app.startAudit(),null,'no data must not produce a safe report');
app.loadScenario('normal');
app.selectAsset('demo-b');
assert.equal(app.inferCandidate(),true);
let s=app.getState();
assert.deepEqual(plain(s.drafts['demo-b'].roles),['database']);
assert.equal(s.drafts['demo-b'].ports,'','SG ports are not approved ports');
assert.equal(s.drafts['demo-b'].sources,'','SG source must not be copied into authorization');
assert.equal(s.profiles['demo-b'],undefined,'candidate is not confirmed');
assert.equal(app.confirmProfile(),false,'confirmation requires preview');
app.previewProfile({roles:['web','database'],exposure:'unknown',ports:'',sources:'',completeSet:false});
assert.equal(app.confirmProfile(),true);
s=app.getState();
assert.equal(s.profiles['demo-b'].version,1);
assert.deepEqual(plain(s.profiles['demo-b'].roles),['web','database']);
assert.equal(s.profiles['demo-b'].sources,'');
app.startAudit();
const first=app.getState().activeTask;
app.advanceRules();
app.cancelAudit();
s=app.getState();
assert.equal(s.tasks[0].status,'cancelled');
assert.equal(s.tasks[0].findings.length,1,'cancel must preserve obtained findings');
assert.equal(app.finishAudit(),false,'cancelled task must not resume');
app.previewProfile({roles:['database'],exposure:'private',ports:'TCP 3306',sources:'only approved app',completeSet:true});
app.confirmProfile();
s=app.getState();
assert.equal(s.profileVersion,2);
assert.equal(s.tasks[0].profileVersion,1,'old task must keep its version');
assert.deepEqual(plain(s.tasks[0].profiles['demo-b'].roles),['web','database'],'old task facts remain frozen');
app.startAudit();
assert.notEqual(app.getState().activeTask,first);
assert.equal(app.getState().tasks[1].profileVersion,2);
app.finishAudit();
app.reviewPlan('本地待办');
s=app.getState();
assert.equal(s.tasks[1].plan,'本地待办');
assert.equal(s.tasks[1].findings[0].status,'不符合（固定示例）','review plan is not remediation');
assert.match(app.buildReport(),/仅原型，非真实审计/);
app.selectAsset('demo-c');
app.inferCandidate();
app.rejectCandidate();
assert.equal(app.getState().profiles['demo-c'],undefined,'reject must not create authorization');
app.loadScenario('model-error');
app.selectAsset('demo-a');
assert.equal(app.inferCandidate(),false);
app.previewProfile({roles:['web'],ports:'',sources:''});
app.confirmProfile();
app.startAudit();app.finishAudit();
s=app.getState();
assert.equal(s.tasks[0].status,'partial');
assert.equal(s.tasks[0].findings.length,1,'model error preserves rules');
app.loadScenario('partial');app.selectAsset('demo-c');
assert.match(elements.get('facts').innerHTML,/不能将其他安全组的端口/);
assert.doesNotMatch(elements.get('facts').innerHTML,/共享组有 Web 端口/);
app.startAudit();app.finishAudit();
assert.equal(app.getState().tasks[0].status,'partial');
console.log('PASS: offline prototype syntax/static IDs/no-network guard; contextual guidance without implicit execution, candidate-confirmation, unknown/reject, multi-role, manual fallback, frozen versions, cancel/partial, and local review-state transitions.');
console.log('LIMIT: minimal DOM substitute; no real browser layout, cloud, model or audit-rule verification.');
