var ErrBusinessTargetUnresolved = errors.New("business target has no matching sealed input")

type ConversationBusinessTarget struct {
	Ref            string       `json:"ref"`
	ConversationID string       `json:"conversation_id"`
	IntentID       string       `json:"intent_id,omitempty"`
	IntentRevision int64        `json:"intent_revision"`
	JobID          string       `json:"job_id"`
	SnapshotID     string       `json:"snapshot_id"`
	Scope          domain.Scope `json:"scope"`
	AssetIDs       []string     `json:"asset_ids"`
}
type BusinessCandidateEvidence struct {
	Document string `json:"document"`
	Field    string `json:"field"`
}
type BusinessRoleCandidate struct {
	Ref                    string                      `json:"ref"`
	AssetID                string                      `json:"asset_id"`
	ServiceID              string                      `json:"service_id,omitempty"`
	Role                   string                      `json:"role"`
	Protocol               string                      `json:"protocol"`
	Ports                  []domain.PortRange          `json:"ports"`
	Evidence               []BusinessCandidateEvidence `json:"evidence"`
	ContradictingEvidence  []BusinessCandidateEvidence `json:"contradicting_evidence"`
	Unknowns               []string                    `json:"unknowns"`
	Questions              []string                    `json:"questions"`
	Decision               string                      `json:"decision"`
	ConflictsWithConfirmed bool                        `json:"conflicts_with_confirmed"`
}
type ConversationBusinessContext struct {
	Target     ConversationBusinessTarget `json:"target"`
	Input      domain.Input               `json:"-"`
	Draft      *ProfileDraft              `json:"draft,omitempty"`
	Preview    *ConfirmationPreview       `json:"preview,omitempty"`
	Candidates []BusinessRoleCandidate    `json:"candidates"`
}
type BusinessAllowedChange struct {
	Complete     bool            `json:"complete"`
	DenyAll      bool            `json:"deny_all"`
	Allowed      []domain.Access `json:"allowed"`
	PublicAccess string          `json:"public_access,omitempty"`
}
type ConversationBusinessPatch struct {
	AssetID    string                 `json:"asset_id"`
	ServiceID  string                 `json:"service_id,omitempty"`
	Role       *RoleChange            `json:"role,omitempty"`
	Allowed    *BusinessAllowedChange `json:"allowed,omitempty"`
	Required   *[]domain.Access       `json:"required,omitempty"`
	Exceptions *[]domain.Exception    `json:"exceptions,omitempty"`
}
type ConversationBusinessRequest struct {
	// ClientDigest is generated by the local router from the original text or
	// typed body before filling current revisions. It is never accepted in JSON.
	ClientDigest          string                      `json:"-"`
	MissingInputs         []string                    `json:"-"`
	Action                string                      `json:"action"`
	ExpectedTargetRef     string                      `json:"expected_target_ref"`
	ExpectedDraftRevision int64                       `json:"expected_draft_revision,omitempty"`
	PreviewID             string                      `json:"preview_id,omitempty"`
	Sections              []string                    `json:"sections,omitempty"`
	Patches               []ConversationBusinessPatch `json:"patches,omitempty"`
	CandidateRef          string                      `json:"candidate_ref,omitempty"`
	UnknownFields         []string                    `json:"unknown_fields,omitempty"`
}

func businessClientDigest(conversation, digest string) string {
	return requestDigest([]string{"conversation-business-v1", conversation, digest})
}

func (s *Store) ConversationBusinessReplay(ctx context.Context, conversation, key, clientDigest string) (result ConversationBusinessResult, found bool, err error) {
	if !validKey(key) || !validKey(clientDigest) {
		return result, false, ErrInputInvalid
	}
	var row struct{ ConversationID, RequestDigest, ResultJSON string }
	r := s.db.WithContext(ctx).Raw("SELECT * FROM conversation_business_requests WHERE request_key=?", key).Scan(&row)
	if r.Error != nil {
		return result, false, r.Error
	}
	if r.RowsAffected == 0 {
		return result, false, nil
	}
	if row.ConversationID != conversation || row.RequestDigest != businessClientDigest(conversation, clientDigest) {
		return result, true, ErrConflict
	}
	if json.Unmarshal([]byte(row.ResultJSON), &result) != nil {
		return result, true, ErrInputInvalid
	}
	result.Replayed = true
	return result, true, nil
}

type ConversationBusinessResult struct {
	State         string                     `json:"state"`
	Reply         string                     `json:"reply"`
	Target        ConversationBusinessTarget `json:"target"`
	Draft         *ProfileDraft              `json:"draft,omitempty"`
	Preview       *ConfirmationPreview       `json:"preview,omitempty"`
	Confirmation  *ConfirmationResult        `json:"confirmation,omitempty"`
	Candidates    []BusinessRoleCandidate    `json:"candidates"`
	UnknownFields []string                   `json:"unknown_fields"`
	MissingInputs []string                   `json:"missing_inputs"`
	Replayed      bool                       `json:"replayed"`
}

func resolveConversationBusiness(tx *gorm.DB, conversation string) (out ConversationBusinessContext, err error) {
	c, e := getConversation(tx, conversation)
	if e != nil {
		return out, e
	}
	if c.Archived {
		return out, ErrConversationArchived
	}
	intent, e := currentIntent(tx, conversation)
	if e != nil && !errors.Is(e, ErrNotFound) {
		return out, e
	}
	hasIntent := e == nil
	if hasIntent && (enum(intent.Status, "needs_clarification", "ambiguous", "clarification_required", "needs_discovery") || len(intent.Selection) == 0 && (intent.Proposal == nil || intent.Proposal.PlanID == "")) {
		return out, ErrBusinessTargetUnresolved
	}
	selectedSnapshot := ""
	if hasIntent {
		if intent.DataPolicy.Mode == "pinned_snapshot" {
			selectedSnapshot = intent.DataPolicy.SnapshotID
		}
		if intent.Proposal != nil && intent.Proposal.PlanID != "" {
			plan, e := planRecord(tx, intent.Proposal.PlanID)
			if e != nil {
				return out, e
			}
			if plan.ConversationID != conversation {
				return out, ErrInputInvalid
			}
			if plan.SnapshotID != "" {
				if selectedSnapshot != "" && selectedSnapshot != plan.SnapshotID {
					return out, ErrBusinessTargetUnresolved
				}
				selectedSnapshot = plan.SnapshotID
			}
		}
	}
	var jobs []Job
	if e = tx.Raw("SELECT * FROM e0_jobs WHERE conversation_id=? AND kind IN ('audit','collect') AND sealed_input IS NOT NULL ORDER BY created_at DESC,id DESC", conversation).Scan(&jobs).Error; e != nil {
		return out, e
	}
	for _, job := range jobs {
		in, e := jobInput(tx, job.ID)
		if e != nil {
			return out, e
		}
		if in.Selection.Kind != "assets" || len(in.Assets) == 0 {
			continue
		}
		if !hasIntent && c.PolicyScopeRef != in.Scope.Ref || hasIntent && (intent.Boundary != in.Scope.Boundary || intent.Direction != in.Scope.Direction) {
			continue
		}
		ids := []string{}
		if hasIntent && len(intent.Selection) > 0 {
			matched := true
			for _, resource := range intent.Selection {
				found := ""
				for _, asset := range in.Assets {
					if resource.AccountRef != in.Scope.AccountRef {
						continue
					}
					if resource.ResourceID != "" && asset.ProviderResourceID == resource.ResourceID && asset.Region == resource.Region && asset.ResourceType == resource.ResourceType || resource.ResourceID == "" && resource.LocalAssetID == asset.ID && resource.IdentityContext == in.Scope.Ref {
						found = asset.ID
						break
					}
				}
				if found == "" || containsPrepared(ids, found) {
					matched = false
					break
				}
				ids = append(ids, found)
			}
			if !matched {
				continue
			}
		} else {
			if hasIntent && (intent.Proposal == nil || intent.Proposal.PlanID != job.PlanID) {
				continue
			}
			ids = append(ids, in.Selection.AssetIDs...)
		}
		p, e := executionPlanForJob(tx, job)
		if e != nil {
			return out, e
		}
		snapshotID := p.SnapshotID
		if snapshotID == "" {
			cloud, e := jobCloudResult(tx, job.ID)
			if e != nil {
				return out, e
			}
			if cloud != nil {
				snapshotID = cloud.Content.SnapshotID
			}
		}
		if snapshotID == "" || selectedSnapshot != "" && selectedSnapshot != snapshotID {
			continue
		}
		frozen, _, e := preparedSelection(tx, snapshotID, domain.Selection{Kind: "assets", AssetIDs: ids})
		if e != nil {
			return out, e
		}
		sort.Strings(ids)
		target := ConversationBusinessTarget{ConversationID: conversation, JobID: job.ID, SnapshotID: snapshotID, Scope: in.Scope, AssetIDs: ids}
		if hasIntent {
			target.IntentID, target.IntentRevision = intent.ID, intent.Revision
		}
		// A goal can advance to a new baseline plan without changing the
		// business objects. Bind drafts to immutable data/scope/member identity;
		// intent revision remains display context, while draft revision and
		// preview CAS protect edits and confirmations.
		target.Ref = "business_target_" + requestDigest(struct {
			ConversationID string
			SnapshotID     string
			Scope          domain.Scope
			Assets         []string
		}{conversation, snapshotID, in.Scope, ids})[:32]
		out.Target, out.Input = target, frozen
		var draftID string
		if e = tx.Raw("SELECT draft_id FROM conversation_business_drafts WHERE conversation_id=? AND target_ref=?", conversation, target.Ref).Scan(&draftID).Error; e != nil {
			return out, e
		}
		if draftID != "" {
			draft, e := getProfileDraft(tx, draftID)
			if e != nil {
				return out, e
			}
			out.Draft = &draft
			if draft.Status == "previewed" && draft.PreviewID != "" {
				var body string
				r := tx.Raw("SELECT body FROM confirmation_previews WHERE id=? AND draft_id=? AND draft_revision=?", draft.PreviewID, draft.ID, draft.Revision).Scan(&body)
				if r.Error != nil {
					return out, r.Error
				}
				var preview ConfirmationPreview
				if r.RowsAffected != 1 || json.Unmarshal([]byte(body), &preview) != nil || preview.ID != draft.PreviewID || preview.DraftID != draft.ID || preview.DraftRevision != draft.Revision {
					return out, ErrInputInvalid
				}
				out.Preview = &preview
			}
		}
		out.Candidates, e = conversationRoleCandidates(tx, job, frozen, target)
		return out, e
	}
	return out, ErrBusinessTargetUnresolved
}

func (s *Store) ConversationBusinessContext(ctx context.Context, conversation string) (out ConversationBusinessContext, err error) {
	err = s.db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { var e error; out, e = resolveConversationBusiness(tx, conversation); return e })
	return
}

func validateConversationDraftBinding(tx *gorm.DB, draftID string) error {
	var bindings []struct{ ConversationID, TargetRef string }
	if e := tx.Raw("SELECT conversation_id,target_ref FROM conversation_business_drafts WHERE draft_id=?", draftID).Scan(&bindings).Error; e != nil {
		return e
	}
	for _, binding := range bindings {
		current, e := resolveConversationBusiness(tx, binding.ConversationID)
		if e != nil || current.Target.Ref != binding.TargetRef || current.Draft == nil || current.Draft.ID != draftID {
			return ErrVersionConflict
		}
	}
	return nil
}

func conversationRoleCandidates(tx *gorm.DB, job Job, input domain.Input, target ConversationBusinessTarget) ([]BusinessRoleCandidate, error) {
	out := []BusinessRoleCandidate{}
	record, e := jobAgentResult(tx, job.ID)
	if e != nil || record == nil || record.Content.Output == nil {
		return out, e
	}
	sealed, e := jobInput(tx, job.ID)
	if e != nil {
		return out, e
	}
	var result *domain.Result
	if job.ResultRef != "" {
		run, e := auditRun(tx, job.ResultRef)
		if e != nil {
			return out, e
		}
		result = &run.Result
	}
	if agentquery.ValidateBoundOutput(sealed, result, *record.Content.Output, record.Content.Bindings) != nil {
		return nil, ErrInputInvalid
	}
	for index, candidate := range record.Content.Output.Roles {
		binding, ok := record.Content.Bindings[candidate.AssetRef]
		ai, si, valid := businessPointer(binding.Field)
		if !ok || binding.Kind != "asset" || binding.Document != "input" || !valid || si != -1 || ai >= len(sealed.Assets) {
			return nil, ErrInputInvalid
		}
		assetID := sealed.Assets[ai].ID
		asset := selectedAsset(&input, assetID)
		if asset == nil {
			continue
		}
		item := BusinessRoleCandidate{Ref: "role_candidate_" + requestDigest([]any{job.ID, index, candidate})[:32], AssetID: assetID, Role: candidate.Role, Protocol: "unknown", Ports: []domain.PortRange{}, Evidence: []BusinessCandidateEvidence{}, ContradictingEvidence: []BusinessCandidateEvidence{}, Unknowns: append([]string{}, candidate.Unknowns...), Questions: append([]string{}, candidate.Questions...), Decision: "pending"}
		if candidate.ServiceRef != "" {
			serviceBinding, exists := record.Content.Bindings[candidate.ServiceRef]
			serviceAI, serviceSI, valid := businessPointer(serviceBinding.Field)
			if !exists || serviceBinding.Kind != "service" || serviceBinding.Document != "input" || !valid || serviceAI != ai || serviceSI < 0 || serviceSI >= len(sealed.Assets[ai].Services) {
				return nil, ErrInputInvalid
			}
			service := sealed.Assets[ai].Services[serviceSI]
			item.ServiceID, item.Protocol, item.Ports = service.ID, service.Protocol, append([]domain.PortRange{}, service.Ports...)
			if current := selectedService(asset, service.ID); current != nil {
				item.ConflictsWithConfirmed = current.RoleStatus == "confirmed" && current.Role != "unknown" && current.Role != candidate.Role
			}
		}
		for _, ref := range candidate.SupportingEvidence {
			evidence, exists := record.Content.Bindings[ref]
			if !exists || !evidence.Returned {
				return nil, ErrInputInvalid
			}
			item.Evidence = append(item.Evidence, BusinessCandidateEvidence{Document: evidence.Document, Field: evidence.Field})
		}
		for _, ref := range candidate.ContradictingEvidence {
			evidence, exists := record.Content.Bindings[ref]
			if !exists || !evidence.Returned {
				return nil, ErrInputInvalid
			}
			item.ContradictingEvidence = append(item.ContradictingEvidence, BusinessCandidateEvidence{Document: evidence.Document, Field: evidence.Field})
		}
		var decision string
		if e := tx.Raw("SELECT decision FROM conversation_role_decisions WHERE conversation_id=? AND target_ref=? AND candidate_ref=? ORDER BY rowid DESC LIMIT 1", target.ConversationID, target.Ref, item.Ref).Scan(&decision).Error; e != nil {
			return nil, e
		}
		if decision != "" {
			item.Decision = decision
		}
		out = append(out, item)
	}
	return out, nil
}

func businessPointer(pointer string) (ai, si int, ok bool) {
	si = -1
	parts := strings.Split(strings.TrimPrefix(pointer, "/"), "/")
	if len(parts) != 2 && len(parts) != 4 || parts[0] != "assets" {
		return 0, -1, false
	}
	ai, e := strconv.Atoi(parts[1])
	if e != nil || ai < 0 || strconv.Itoa(ai) != parts[1] {
		return 0, -1, false
	}
	if len(parts) == 4 {
		if parts[2] != "services" {
			return 0, -1, false
		}
		si, e = strconv.Atoi(parts[3])
		if e != nil || si < 0 || strconv.Itoa(si) != parts[3] {
			return 0, -1, false
		}
	}
	return ai, si, true
}

func (s *Store) ApplyConversationBusiness(ctx context.Context, conversation, key string, request ConversationBusinessRequest) (result ConversationBusinessResult, err error) {
	if !validKey(key) || !attemptAlias(request.ExpectedTargetRef) || !enum(request.Action, "read", "edit", "preview", "confirm", "reject_draft", "accept_candidate", "reject_candidate", "keep_unknown") || len(request.UnknownFields) > 20 {
		return result, ErrInputInvalid
	}
	if _, e := marshalBounded(request, 1<<20); e != nil {
		return result, e
	}
	for _, field := range request.UnknownFields {
		if !enum(field, "role", "management_sources", "allowed_sources", "required_sources", "required_targets", "service", "exception_authorization") {
			return result, ErrInputInvalid
		}
	}
	digest := requestDigest(struct {
		Conversation string
		Request      ConversationBusinessRequest
	}{conversation, request})
	if request.ClientDigest != "" {
		if !validKey(request.ClientDigest) {
			return result, ErrInputInvalid
		}
		digest = businessClientDigest(conversation, request.ClientDigest)
	}
	err = s.db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		var replay struct{ ConversationID, RequestDigest, ResultJSON string }
		r := tx.Raw("SELECT * FROM conversation_business_requests WHERE request_key=?", key).Scan(&replay)
		if r.Error != nil {
			return r.Error
		}
		if r.RowsAffected > 0 {
			if replay.ConversationID != conversation || replay.RequestDigest != digest {
				return ErrConflict
			}
			if json.Unmarshal([]byte(replay.ResultJSON), &result) != nil {
				return ErrInputInvalid
			}
			result.Replayed = true
			return nil
		}
		current, e := resolveConversationBusiness(tx, conversation)
		if e != nil {
			return e
		}
		if current.Target.Ref != request.ExpectedTargetRef {
			return ErrVersionConflict
		}
		result = ConversationBusinessResult{State: "draft", Target: current.Target, Draft: current.Draft, Candidates: current.Candidates, UnknownFields: append([]string{}, request.UnknownFields...), MissingInputs: append([]string{}, request.MissingInputs...)}
		local := &Store{db: tx, SQL: s.SQL}
		var chosen *BusinessRoleCandidate
		if request.CandidateRef != "" {
			for i := range current.Candidates {
				if current.Candidates[i].Ref == request.CandidateRef {
					chosen = &current.Candidates[i]
					break
				}
			}
			if chosen == nil {
				return ErrInputInvalid
			}
		}
		if enum(request.Action, "accept_candidate", "reject_candidate") && chosen == nil {
			return ErrInputInvalid
		}
		if request.Action == "accept_candidate" {
			request.Patches = []ConversationBusinessPatch{{AssetID: chosen.AssetID, ServiceID: chosen.ServiceID, Role: &RoleChange{Role: chosen.Role, Protocol: chosen.Protocol, Ports: chosen.Ports}}}
		}
		needsDraft := enum(request.Action, "edit", "preview", "accept_candidate", "confirm", "reject_draft")
		if needsDraft && (current.Draft == nil || !enum(current.Draft.Status, "draft", "previewed")) {
			if enum(request.Action, "confirm", "reject_draft") {
				return ErrVersionConflict
			}
			draft, e := local.CreateProfileDraft(ctx, CreateDraftRequest{SnapshotID: current.Target.SnapshotID, AssetIDs: current.Target.AssetIDs})
			if e != nil {
				return e
			}
			quietConversationChanges(draft.Changes)
			draft, e = local.UpdateProfileDraft(ctx, draft.ID, UpdateDraftRequest{ExpectedDraftRevision: draft.Revision, Changes: draft.Changes})
			if e != nil {
				return e
			}
			if e = tx.Exec("INSERT INTO conversation_business_drafts(conversation_id,target_ref,draft_id) VALUES(?,?,?) ON CONFLICT(conversation_id,target_ref) DO UPDATE SET draft_id=excluded.draft_id", conversation, current.Target.Ref, draft.ID).Error; e != nil {
				return e
			}
			current.Draft = &draft
		}
		if current.Draft != nil && request.ExpectedDraftRevision > 0 && current.Draft.Revision != request.ExpectedDraftRevision {
			return ErrVersionConflict
		}
		if enum(request.Action, "edit", "accept_candidate") {
			if len(request.Patches) == 0 {
				return ErrInputInvalid
			}
			draft, e := applyConversationPatches(ctx, local, current, request.Patches)
			if e != nil {
				return e
			}
			current.Draft = &draft
		}
		if enum(request.Action, "edit", "accept_candidate", "preview") {
			preview, e := local.PreviewProfileDraft(ctx, current.Draft.ID)
			if e != nil {
				return e
			}
			result.Preview = &preview
			result.State = "preview_required"
		}
		if request.Action == "confirm" {
			if request.ExpectedDraftRevision < 1 || request.PreviewID == "" {
				return ErrInputInvalid
			}
			confirmed, e := local.ConfirmProfileDraft(ctx, current.Draft.ID, ConfirmDraftRequest{PreviewID: request.PreviewID, ExpectedDraftRevision: request.ExpectedDraftRevision, ConfirmedSections: request.Sections}, "business_"+requestDigest([]string{conversation, key}))
			if e != nil {
				return e
			}
			result.Confirmation = &confirmed
			result.State = "confirmed"
		}
		if request.Action == "reject_draft" {
			if request.ExpectedDraftRevision < 1 {
				return ErrInputInvalid
			}
			rejected, e := local.RejectProfileDraft(ctx, current.Draft.ID, request.ExpectedDraftRevision, "business_"+requestDigest([]string{conversation, key}))
			if e != nil {
				return e
			}
			result.Confirmation = &rejected
			result.State = "rejected"
		}
		if request.Action == "keep_unknown" {
			result.State = "unknown_preserved"
		}
		if chosen != nil && enum(request.Action, "accept_candidate", "reject_candidate", "keep_unknown") {
			decision := "unknown"
			if request.Action == "accept_candidate" {
				decision = "accepted_for_preview"
			}
			if request.Action == "reject_candidate" {
				decision = "rejected"
				result.State = "candidate_rejected"
			}
			id, e := opaqueID("role_decision")
			if e != nil {
				return e
			}
			if e = tx.Exec("INSERT INTO conversation_role_decisions(id,conversation_id,target_ref,candidate_ref,decision,request_key,created_at) VALUES(?,?,?,?,?,?,?)", id, conversation, current.Target.Ref, chosen.Ref, decision, key, now()).Error; e != nil {
				return e
			}
			for i := range result.Candidates {
				if result.Candidates[i].Ref == chosen.Ref {
					result.Candidates[i].Decision = decision
				}
			}
		}
		if current.Draft != nil {
			draft, e := getProfileDraft(tx, current.Draft.ID)
			if e != nil {
				return e
			}
			result.Draft = &draft
		}
		body, e := marshalBounded(result, 2<<20)
		if e != nil {
			return e
		}
		return tx.Exec("INSERT INTO conversation_business_requests(request_key,conversation_id,request_digest,result_json) VALUES(?,?,?,?)", key, conversation, digest, string(body)).Error
	})
	return result, err
}

func quietConversationChanges(changes []AssetDraftChange) {
	for i := range changes {
		for j := range changes[i].Roles {
			changes[i].Roles[j].Declared = businessBool(false)
		}
		if access := changes[i].Access; access != nil {
			access.AllowedDeclared, access.ExceptionsDeclared = businessBool(false), businessBool(false)
			for j := range access.Services {
				access.Services[j].AllowedDeclared, access.Services[j].RequiredDeclared = businessBool(false), businessBool(false)
			}
		}
	}
}
func businessBool(v bool) *bool { return &v }

// A conversation can confirm one section while keeping the other explicitly
// edited section in the same shared draft. The newly saved heads become its
// base; the old preview is invalidated and must be generated again.
func advanceConversationDraftAfterConfirmation(tx *gorm.DB, draft ProfileDraft, sections []string, heads []AssetHeadVersion, actionID, at string) (bool, error) {
	var bound int64
	if e := tx.Raw("SELECT count(*) FROM conversation_business_drafts WHERE draft_id=?", draft.ID).Scan(&bound).Error; e != nil {
		return false, e
	}
	if bound == 0 {
		return false, nil
	}
	pending := false
	for _, section := range []string{"roles", "access"} {
		if !containsSection(sections, section) && sectionAvailable(draft.Changes, section) {
			pending = true
		}
	}
	if !pending {
		return false, nil
	}
	for i := range draft.Changes {
		change := &draft.Changes[i]
		if containsSection(sections, "roles") {
			for j := range change.Roles {
				change.Roles[j].Declared = businessBool(false)
			}
		}
		if containsSection(sections, "access") && change.Access != nil {
			change.Access.AllowedDeclared, change.Access.ExceptionsDeclared = businessBool(false), businessBool(false)
			for j := range change.Access.Services {
				change.Access.Services[j].AllowedDeclared, change.Access.Services[j].RequiredDeclared = businessBool(false), businessBool(false)
			}
		}
	}
	body, e := marshalBounded(draft.Changes, 1<<20)
	if e != nil {
		return false, e
	}
	bases, e := marshalBounded(heads, 1<<20)
	if e != nil {
		return false, e
	}
	r := tx.Exec("UPDATE profile_drafts SET status='draft',revision=revision+1,confirmation_id=?,preview_id=NULL,body=?,base_json=?,updated_at=? WHERE id=? AND revision=?", actionID, string(body), string(bases), at, draft.ID, draft.Revision)
	if r.Error != nil {
		return false, r.Error
	}
	if r.RowsAffected != 1 {
		return false, ErrVersionConflict
	}
	return true, nil
}

func applyConversationPatches(ctx context.Context, s *Store, current ConversationBusinessContext, patches []ConversationBusinessPatch) (ProfileDraft, error) {
	draft := *current.Draft
	encoded, e := marshalBounded(draft.Changes, 1<<20)
	if e != nil {
		return draft, e
	}
	draft.Changes = nil
	if json.Unmarshal(encoded, &draft.Changes) != nil {
		return draft, ErrInputInvalid
	}
	for _, patch := range patches {
		if !containsPrepared(current.Target.AssetIDs, patch.AssetID) {
			return draft, ErrInputInvalid
		}
		index := -1
		for i := range draft.Changes {
			if draft.Changes[i].AssetID == patch.AssetID {
				index = i
				break
			}
		}
		if index < 0 {
			return draft, ErrInputInvalid
		}
		change := &draft.Changes[index]
		serviceID := patch.ServiceID
		if patch.Role != nil {
			role := *patch.Role
			if role.ServiceID != "" && role.ServiceID != serviceID {
				return draft, ErrInputInvalid
			}
			role.ServiceID, role.Declared = serviceID, businessBool(true)
			found := false
			for i := range change.Roles {
				if serviceID != "" && change.Roles[i].ServiceID == serviceID {
					change.Roles[i] = role
					found = true
					break
				}
			}
			if serviceID != "" && !found {
				return draft, ErrInputInvalid
			}
			if !found {
				change.Roles = append(change.Roles, role)
				draft, e = s.UpdateProfileDraft(ctx, draft.ID, UpdateDraftRequest{ExpectedDraftRevision: draft.Revision, Changes: draft.Changes})
				if e != nil {
					return draft, e
				}
				change = &draft.Changes[index]
				serviceID = change.Roles[len(change.Roles)-1].ServiceID
			}
		}
		if change.Access == nil {
			change.Access = &AssetAccessChange{AllowedDeclared: businessBool(false), ExceptionsDeclared: businessBool(false), Allowed: []domain.Access{}, Services: []ServiceAccessChange{}, Exceptions: []domain.Exception{}}
		}
		access := change.Access
		if serviceID == "" {
			if patch.Required != nil {
				return draft, ErrInputInvalid
			}
			if patch.Allowed != nil {
				access.AllowedDeclared = businessBool(true)
				access.AllowedComplete, access.DenyAll, access.Allowed = patch.Allowed.Complete, patch.Allowed.DenyAll, patch.Allowed.Allowed
			}
		} else {
			known := false
			for _, role := range change.Roles {
				if role.ServiceID == serviceID {
					known = true
					break
				}
			}
			if !known {
				return draft, ErrInputInvalid
			}
			si := -1
			for i := range access.Services {
				if access.Services[i].ServiceID == serviceID {
					si = i
					break
				}
			}
			if si < 0 {
				access.Services = append(access.Services, ServiceAccessChange{ServiceID: serviceID, PublicAccess: "unknown", Allowed: []domain.Access{}, Required: []domain.Access{}, AllowedDeclared: businessBool(false), RequiredDeclared: businessBool(false)})
				si = len(access.Services) - 1
			}
			item := &access.Services[si]
			if patch.Allowed != nil {
				item.AllowedDeclared = businessBool(true)
				item.PublicAccess = patch.Allowed.PublicAccess
				if item.PublicAccess == "" {
					item.PublicAccess = "unknown"
				}
				item.AllowedComplete, item.DenyAll, item.Allowed = patch.Allowed.Complete, patch.Allowed.DenyAll, patch.Allowed.Allowed
			}
			if patch.Required != nil {
				item.RequiredDeclared = businessBool(true)
				item.RequiredConfirmed = true
				item.Required = *patch.Required
			}
		}
		if patch.Exceptions != nil {
			access.ExceptionsDeclared = businessBool(true)
			access.Exceptions = *patch.Exceptions
		}
	}
	return s.UpdateProfileDraft(ctx, draft.ID, UpdateDraftRequest{ExpectedDraftRevision: draft.Revision, Changes: draft.Changes})
}
